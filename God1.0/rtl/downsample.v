//======================================================================
// Module: downsample
// Function: 流式降采样 1280×960 → 64×48
//   每 20 像素取 1, 每 20 行取 1
//   输出 64×48 = 3072 像素/帧
//
//   v5 (2026-08-01):
//     - 摄像头分辨率寄存器未生效, 实际输出 ~1280×960 (960行, 行长~2560字节)。
//       采集已适配 1280×960 (pix_x 0-1279, pix_y 0-959)。
//     - 降采样因子 20 (1280/20=64, 960/20=48), 乘倒数 3277 (×3277>>16 = /20)。
//     - 硬边界裁剪 x_div20<64 && y_div20<48, 每帧恒 3072 采样, 缓冲不溢出。
//     - 避开 HDL `/` (cbx_lpm_divide.dll 打不开) 与 `*` 推断。
// Clock:  pclk 域
//======================================================================
module downsample (
    input  wire        pclk,
    input  wire        rst_n,
    input  wire [7:0]  y_data,        // Y 通道 (来自 ov5640_capture)
    input  wire        y_valid,       // Y 有效脉冲
    input  wire [10:0] pix_x,         // 全分辨率列坐标 0-1279
    input  wire [10:0] pix_y,         // 全分辨率行坐标 0-959
    output reg  [7:0]  ds_y_data,     // 降采样后 Y 值
    output reg         ds_y_valid,    // 降采样有效脉冲
    output reg  [6:0]  ds_pix_x,      // 0-63
    output reg  [5:0]  ds_pix_y       // 0-47
);

    //------------------------------------------------------------------
    // 范围保护: 1280×960 窗口内
    //------------------------------------------------------------------
    wire in_range = (pix_x < 11'd1280) && (pix_y < 11'd960);

    //------------------------------------------------------------------
    // 直接计算网格坐标 (/20), 用乘倒数: x*3277 >> 16
    //   3277/65536 ≈ 0.050003, 对 x≤2047 误差 < 0.007 < 最小余数 0.05, 精确.
    //   3277 = 2048+1024+128+64+8+4+1 → 移位加法实现
    //------------------------------------------------------------------
    wire [23:0] x_p  = (pix_x << 11) + (pix_x << 10)
                     + (pix_x << 7)  + (pix_x << 6)
                     + (pix_x << 3)  + (pix_x << 2)
                     + pix_x;
    wire [23:0] y_p  = (pix_y << 11) + (pix_y << 10)
                     + (pix_y << 7)  + (pix_y << 6)
                     + (pix_y << 3)  + (pix_y << 2)
                     + pix_y;
    wire [9:0] x_div20 = x_p[23:16];
    wire [9:0] y_div20 = y_p[23:16];

    // 整除判断: x_div20*20 == pix_x  (x_div20*20 = (x<<4)+(x<<2))
    wire x_at_grid = ((x_div20 << 4) + (x_div20 << 2)) == pix_x;
    wire y_at_grid = ((y_div20 << 4) + (y_div20 << 2)) == pix_y;

    //------------------------------------------------------------------
    // 输出寄存
    //------------------------------------------------------------------
    always @(posedge pclk or negedge rst_n) begin
        if (!rst_n) begin
            ds_y_data  <= 8'd0;
            ds_y_valid <= 1'b0;
            ds_pix_x   <= 7'd0;
            ds_pix_y   <= 6'd0;
        end else begin
            ds_y_valid <= 1'b0;   // 默认低
            // 64×48 硬边界裁剪: 只取前 64×48 个网格点 (每帧恒 3072 采样)
            if (y_valid && x_at_grid && y_at_grid && in_range
                && (x_div20 < 10'd64) && (y_div20 < 10'd48)) begin
                ds_y_data  <= y_data;
                ds_y_valid <= 1'b1;
                ds_pix_x   <= x_div20[6:0];   // 0-63
                ds_pix_y   <= y_div20[5:0];   // 0-47
            end
        end
    end

endmodule
