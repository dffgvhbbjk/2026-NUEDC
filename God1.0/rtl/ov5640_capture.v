//======================================================================
// Module: ov5640_capture
// Function: OV5640 图像采集 + 单通道提取 (作为灰度)
//   官方配置为 RGB565 8-bit DVP: 每像素 2 字节, 偶数位置字节 = 像素第 1 字节
//   (红通道高字节), 取偶数位置字节作为灰度输出, 丢弃第 2 字节 (G/B 低位)
//   黑矩形/白纸在单通道上对比明显, gap 检测照常工作.
//   每行 640 像素 = 1280 字节, 取 640 个字节 (pix_x 0-639)
//   容错: 若实际行长 > 640 像素 (DVP 输出尺寸未按配置生效时),
//   byte_cnt 饱和不回卷, 超出的像素丢弃 (pix_x 保持 1023),
//   配合 downsample 的 in_range (x<800) 过滤, 每行仍输出 64 个采样
//
//   VSYNC 上升沿 → frame_sync 脉冲, pix_y 清零
//   HREF 上升沿 → 新行开始, byte_cnt 清零
//   HREF 下降沿 → pix_y++
//   byte_cnt[0]==0 时输出 Y, pix_x = byte_cnt/2
//
// Clock:  pclk 域 (OV5640 像素时钟 ~24MHz)
//======================================================================
module ov5640_capture (
    input  wire        pclk,          // OV5640 PCLK
    input  wire        rst_n,
    // OV5640 DVP 接口
    input  wire [7:0]  cam_data,      // D[7:0]
    input  wire        cam_href,      // 行有效
    input  wire        cam_vsync,     // 帧同步
    // 输出 (pclk 域)
    output reg  [7:0]  y_data,        // Y 通道亮度
    output reg         y_valid,       // Y 有效脉冲
    output reg  [10:0] pix_x,         // 列坐标 0-1279 (适配摄像头实际 ~1280×960)
    output reg  [10:0] pix_y,         // 行坐标 0-959
    output reg         frame_sync     // 帧起始脉冲 (1 拍)
);

    //------------------------------------------------------------------
    // 边沿检测
    //------------------------------------------------------------------
    reg vsync_d1;
    reg href_d1;

    //------------------------------------------------------------------
    // 字节计数器 (行内)
    //   0-1599, 偶数为 Y, 奇数为 U/V
    //   饱和计数 (2026-07-28 花屏修复):
    //   若摄像头实际行长 > 2047 拍 (如 DVP 输出尺寸未按配置生效,
    //   实测 ~2620 拍/行), byte_cnt 在 2047 处饱和保持, 不回卷.
    //   否则 pix_x 会从 0 重新计数, 造成行内重复采样 (花屏).
    //------------------------------------------------------------------
    reg [11:0] byte_cnt;   // 0-2559 (1280像素×2字节; 饱和上限 2559), 需 12 bit

    //------------------------------------------------------------------
    // 主逻辑
    //------------------------------------------------------------------
    always @(posedge pclk or negedge rst_n) begin
        if (!rst_n) begin
            vsync_d1   <= 1'b0;
            href_d1    <= 1'b0;
            byte_cnt   <= 12'd0;
            pix_x      <= 11'd0;
            pix_y      <= 11'd0;
            y_data     <= 8'd0;
            y_valid    <= 1'b0;
            frame_sync <= 1'b0;
        end else begin
            //--------------------------------------------------------------
            // 延迟用于边沿检测
            //--------------------------------------------------------------
            vsync_d1 <= cam_vsync;
            href_d1  <= cam_href;

            //--------------------------------------------------------------
            // 默认值
            //--------------------------------------------------------------
            y_valid    <= 1'b0;
            frame_sync <= 1'b0;

            //--------------------------------------------------------------
            // VSYNC 上升沿: 新帧开始
            //   pix_y 清零, 产生 frame_sync 脉冲
            //--------------------------------------------------------------
            if (cam_vsync && !vsync_d1) begin
                frame_sync <= 1'b1;
                pix_y      <= 10'd0;
            end

            //--------------------------------------------------------------
            // HREF 电平采集 (YUV422 字节对齐)
            //   OV5640 YUV422 8-bit DVP 字节流:
            //     索引 0=Y0, 1=U0, 2=Y1, 3=V0, 4=Y2, 5=U1, 6=Y3, 7=V1, ...
            //   偶数索引 (byte_cnt[0]==0) 为 Y, 奇数索引 (byte_cnt[0]==1) 为 U/V
            //
            //   HREF 与 D[7:0] 在 PCLK 下降沿同步更新, FPGA 在 PCLK 上升沿
            //   同步采样到 HREF=1 和 D=Y0, 无需跳过 HREF 上升沿那拍.
            //
            //   时序 (byte_cnt 在 HREF=0 期间已清零):
            //     T 拍 (HREF 上升沿): byte_cnt=0, cam_data=Y0, 采集 Y0 ✓
            //     T+1 拍: byte_cnt=1, cam_data=U0, 跳过
            //     T+2 拍: byte_cnt=2, cam_data=Y1, 采集 Y1 ✓
            //     T+3 拍: byte_cnt=3, cam_data=V0, 跳过
            //   pix_x = byte_cnt / 2 (byte_cnt=0→0, =2→1, =4→2, ...)
            //
            //   注: 之前的实现 (跳过 HREF 上升沿 + byte_cnt[0]==1 采集)
            //   实际采集的是 U0,V0,U1,V1,... 全部为色度字节, 导致花屏.
            //--------------------------------------------------------------
            if (cam_href) begin
                // 偶数字节 (byte_cnt[0]==0) 为 Y, 输出
                //   byte_cnt=0 → Y0, =2 → Y1, ..., =1598 → Y799
                if (byte_cnt[0] == 1'b0) begin
                    y_data  <= cam_data;
                    y_valid <= 1'b1;
                    pix_x   <= {1'b0, byte_cnt[11:1]};  // byte_cnt / 2 → 0-1279
                end
                // 饱和计数: 计到 2559 后保持, 防止回卷导致 pix_x 重复计数
                // (行长 > 2559 拍时, 多余字节丢弃, pix_x 停在 1279)
                if (byte_cnt < 12'd2559)
                    byte_cnt <= byte_cnt + 1'b1;
            end
            //--------------------------------------------------------------
            // HREF 无效: byte_cnt 清零, 为下一行准备
            //--------------------------------------------------------------
            else begin
                byte_cnt <= 11'd0;
            end

            //--------------------------------------------------------------
            // HREF 下降沿: 行末, pix_y 递增
            //   (下一行的 HREF 有效时 pix_y 已是正确值)
            //--------------------------------------------------------------
            if (!cam_href && href_d1) begin
                if (pix_y < 11'd959)
                    pix_y <= pix_y + 1'b1;
            end
        end
    end

endmodule
